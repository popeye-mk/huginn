// Field regression (Win 11, 0.9.0): the IP_ADAPTER_INFO struct walk reported
// the DHCP server as "255" where the real answer was 10.0.0.10. The registry
// is the documented, locale-proof source; this pins its format.
func TestDHCPFromRegistry(t *testing.T) {
	const out = `
HKEY_LOCAL_MACHINE\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\{aaaa-1111}
    DhcpIPAddress    REG_SZ    10.0.0.50
    DhcpServer    REG_SZ    10.0.0.10
    LeaseTerminatesTime    REG_DWORD    0x689c1f00

HKEY_LOCAL_MACHINE\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters\Interfaces\{bbbb-2222}
    DhcpIPAddress    REG_SZ    0.0.0.0
`
	leases := DHCPFromRegistry(out)
	if len(leases) != 2 {
		t.Fatalf("want 2 interface blocks, got %d: %+v", len(leases), leases)
	}
	var found bool
	for _, l := range leases {
		if l.IPAddress == "10.0.0.50" {
			found = true
			if l.Server != "10.0.0.10" {
				t.Errorf("server = %q, want 10.0.0.10 (the field bug reported \"255\")", l.Server)
			}
			if l.ExpiryUTC != 0x689c1f00 {
				t.Errorf("expiry = %d, want the parsed REG_DWORD", l.ExpiryUTC)
			}
		}
	}
	if !found {
		t.Error("the interface holding the lease was not parsed")
	}
}

