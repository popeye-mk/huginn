// Bug #31 (Zorin, 0.9.22) — the most instructive bug in this project so far.
//
// The counter counted every "link is down" line in the journal. On a laptop
// working perfectly over Wi-Fi, 46 of them belonged to enp7s0: an unplugged
// Realtek ethernet port, which is what r8169 does with an empty socket. The
// tool reported "the link went down repeatedly" and the finding was cited for
// weeks as a genuine fault the tool had found.
//
// The number was right. The subject of the sentence was wrong.
func TestFlapsAreAttributedToTheInterfaceInUse(t *testing.T) {
	// The real shape, from popeye-mk's journal.
	lines := []string{
		"1721400000.0 host kernel: r8169 0000:07:00.0 enp7s0: Link is Down",
		"1721400100.0 host kernel: r8169 0000:07:00.0 enp7s0: Link is Down",
		"1721400200.0 host kernel: r8169 0000:07:00.0 enp7s0: Link is Down",
		"1721400300.0 host kernel: iwlwifi 0000:02:00.0 wlp2s0: Link is Down",
	}

	// On Wi-Fi: only the ONE wireless flap is this machine's connection.
	onWifi := MineEvents(lines, "wlp2s0")
	if onWifi.LinkFlaps != 1 {
		t.Errorf("primary flaps = %d, want 1 — the unplugged ethernet port must not count",
			onWifi.LinkFlaps)
	}
	if onWifi.OtherFlaps["enp7s0"] != 3 {
		t.Errorf("enp7s0 flaps = %d, want 3 reported separately", onWifi.OtherFlaps["enp7s0"])
	}
	if !onWifi.Attributed {
		t.Error("attribution was possible and was not claimed")
	}

	// Plugged into ethernet instead: the same lines mean the opposite.
	onWired := MineEvents(lines, "enp7s0")
	if onWired.LinkFlaps != 3 {
		t.Errorf("wired primary flaps = %d, want 3", onWired.LinkFlaps)
	}
	if onWired.OtherFlaps["wlp2s0"] != 1 {
		t.Errorf("wifi flaps should now be the OTHER interface: %v", onWired.OtherFlaps)
	}

	// No primary known: count, but do not claim they are the machine's link.
	// Silence would hide a real fault; attribution would invent one.
	unknown := MineEvents(lines, "")
	if unknown.Attributed {
		t.Error("claimed attribution with no primary interface")
	}
	if unknown.LinkFlaps != 4 {
		t.Errorf("unattributed count = %d, want all 4 visible as evidence", unknown.LinkFlaps)
	}

	// The peak-hour clustering must only see the primary's flaps, or the
	// "it happens around 14:00" claim describes the wrong interface.
	if len(onWifi.FlapHours) > 1 {
		t.Errorf("peak-hour buckets polluted by other interfaces: %v", onWifi.FlapHours)
	}
}

func TestIfaceInLogLine(t *testing.T) {
	for _, tc := range []struct{ line, want string }{
		{"r8169 0000:07:00.0 enp7s0: Link is Down", "enp7s0"},
		{"e1000e 0000:00:1f.6 eno1: Link is Down", "eno1"},
		{"host systemd-networkd[700]: wlp2s0: Lost carrier", "wlp2s0"},
		{"host kernel: eth0: carrier lost", "eth0"},
		// Nothing name-shaped before the message: must return "" so the caller
		// files it as unattributable rather than blaming the primary.
		{"kernel: Link is Down", ""},
		{"Link is Down", ""},
		{"", ""},
	} {
		if got := IfaceInLogLine(tc.line); got != tc.want {
			t.Errorf("IfaceInLogLine(%q) = %q, want %q", tc.line, got, tc.want)
		}
	}
}
