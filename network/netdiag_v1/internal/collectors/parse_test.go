// Bug #23: the input policy used to default to "accept" and only be revised to
// "drop", so a ruleset that never stated one was reported as wide open.
func TestFirewallPolicyIsNeverAssumed(t *testing.T) {
	// nft doing only NAT: no filter input hook anywhere.
	natOnly := `
table ip nat {
	chain postrouting {
		type nat hook postrouting priority srcnat; policy accept;
		oifname "eth0" masquerade
	}
}`
	s := SummariseNftables(natOnly)
	if s.InputPolicy != "" {
		t.Errorf("input policy %q invented from a ruleset with no input hook", s.InputPolicy)
	}

	drop := `
table inet filter {
	chain input {
		type filter hook input priority 0; policy drop;
		ct state established,related accept
		tcp dport 22 accept
	}
}`
	s = SummariseNftables(drop)
	if s.InputPolicy != "drop" {
		t.Errorf("input policy = %q, want drop", s.InputPolicy)
	}
	if s.RuleCount < 2 {
		t.Errorf("rule count = %d, want the two accept rules counted", s.RuleCount)
	}

	// reject is a real nft policy and used to be silently read as accept.
	reject := "\tchain input {\n\t\ttype filter hook input priority 0; policy reject;\n\t}"
	if got := SummariseNftables(reject).InputPolicy; got != "reject" {
		t.Errorf("reject policy read as %q", got)
	}

	if got := SummariseNftables("").Measured; got {
		t.Error("an empty ruleset reported itself as measured")
	}
}

