func TestDefaultGatewayFromRoute(t *testing.T) {
	// Captured from the laptop: gateway 192.168.1.1 as little-endian hex.
	const routeTable = `Iface	Destination	Gateway 	Flags	RefCnt	Use	Metric	Mask		MTU	Window	IRTT
wlp2s0	00000000	01B2A8C0	0003	0	0	600	00000000	0	0	0
wlp2s0	00B2A8C0	00000000	0001	0	0	600	00FFFFFF	0	0	0
`
	if got := DefaultGatewayFromRoute(routeTable); got != "192.168.1.1" {
		t.Errorf("gateway = %q, want 192.168.1.1", got)
	}

	// A machine with an address but NO default route must yield "", not a
	// plausible-looking wrong answer.
	const noDefault = `Iface	Destination	Gateway 	Flags	RefCnt	Use	Metric	Mask		MTU	Window	IRTT
eth0	0032A8C0	00000000	0001	0	0	0	00FFFFFF	0	0	0
`
	if got := DefaultGatewayFromRoute(noDefault); got != "" {
		t.Errorf("no default route should give empty, got %q", got)
	}

	// Garbage in, silence out.
	if got := DefaultGatewayFromRoute("not a route table"); got != "" {
		t.Errorf("garbage gave %q", got)
	}
}

