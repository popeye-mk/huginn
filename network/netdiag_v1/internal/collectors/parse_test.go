// dhclient APPENDS leases, so a file holds every lease the interface ever had.
// Taking the first match reports an expiry from months ago and claims the
// lease has lapsed on a machine whose networking is fine.
func TestLeaseExpiryTakesTheNewest(t *testing.T) {
	const leases = `
lease {
  interface "eno1";
  option dhcp-server-identifier 192.168.1.1;
  expire 3 2026/01/02 12:00:00;
}
lease {
  interface "eno1";
  option dhcp-server-identifier 192.168.1.1;
  expire 5 2026/07/22 09:30:00;
}
lease {
  interface "eno1";
  expire 4 2026/03/15 18:00:00;
}
`
	got, ok := LeaseExpiryFrom(leases)
	if !ok {
		t.Fatal("no expiry found in a file full of them")
	}
	want := time.Date(2026, 7, 22, 9, 30, 0, 0, time.UTC)
	if !got.Equal(want) {
		t.Errorf("expiry = %s, want the NEWEST lease %s", got, want)
	}

	if _, ok := LeaseExpiryFrom("lease {\n  interface \"eno1\";\n}"); ok {
		t.Error("a lease with no expire line reported one anyway")
	}
	if _, ok := LeaseExpiryFrom(""); ok {
		t.Error("empty input produced an expiry")
	}
	// A malformed date must not become "expired now", which would fire a
	// lease-expiry finding on a healthy machine.
	if _, ok := LeaseExpiryFrom("expire 3 not/a/date 99:99:99;"); ok {
		t.Error("garbage date parsed as a real expiry")
	}
}

